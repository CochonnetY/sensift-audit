"""键名构造器：统一处理中文键名、前缀粘连、全角冒号。

真实设备/业务日志里同一个字段至少有三种写法，少支持一种就是漏报：

    英文前缀：db_password=xxx    device_secret: xxx    myApiKey=xxx
    中文键名：数据库密码：xxx     设备密钥=xxx          序列号:xxx
    全角冒号：密码：xxx          令牌：xxx

原先这 15 条规则的键名是英文字面量直接写进正则的，导致两类系统性漏报：

1. **中文键名完全扫不到**——`密码:Passw0rd`、`序列号:SN2024AB1234` 一条不报；
2. **带前缀的键名扫不到**——`db_password` 里 `password` 前面是下划线，
   Python 的 `\\b` 认为 `_` 是词字符，边界不成立，整条漏掉。

这里把「键名 + 分隔符」抽成构造器，规则里只声明英文名与中文别名。
左边界用 `(?<![A-Za-z0-9])` 而不是 `\\b`，就是为了让 `_` 前缀能过。
"""

from __future__ import annotations

# 全角冒号与全角等号必须进来：中文日志里 `密码：xxx` / `密码＝xxx`
# 比半角写法更常见。引号与空白可选，同时吃下 `key=value` / `"key": "value"`
# 两种写法。
_SEP = r"""["']?\s*[:：=＝]\s*["']?"""


def key_re(en: str, *zh: str, prefix: int = 0) -> str:
    """构造「键名 + 分隔符」片段，后面直接接值捕获组。

    Args:
        en: 英文键名的正则片段，支持内部 `[_\\-]?`（如 `access[_\\-]?key`）。
        zh: 中文别名，按正则片段处理，可自带负向断言。
        prefix: 允许的粘连前缀字符数上限。`db_password` / `myApiKey` 这类
            前缀是常态，此时传 12；`sn` / `sid` 这类短键名传 0，保持严格
            左边界，避免 `xxxsn=` 误命中。

    中文别名里的负向断言很重要：`密码策略:`、`密钥管理:` 本身不是凭据，
    光靠值校验挡不住（`密码策略: 8位以上` 的值也长得像口令）。
    """
    alts: list[str] = []
    if prefix > 0:
        alts.append(rf"[A-Za-z0-9_\-]{{0,{prefix}}}(?:{en})")
    else:
        alts.append(rf"(?:{en})")
    alts.extend(zh)
    body = "|".join(alts)
    # 用局部标志 (?i:...) 而不是全局 (?i)：键名片段可能被拼在别的正则中段，
    # 全局内联标志在 Python 里要求出现在 pattern 开头，拼接后会直接报错。
    return rf"(?<![A-Za-z0-9])(?i:(?:{body})(?![A-Za-z0-9])){_SEP}"


# 反复使用的中文反证：这些词后面跟值，是策略/说明而不是凭据。
_NOT_POLICY = r"(?!策略|强度|长度|错误|输入|框|重置|修改|找回|规则|管理|复杂度|等级|过期|校验|要求|提示)"
